export async function checkPackageNames(packageJSONFiles) {
	const errors = [];

	packageJSONFiles.forEach((pkg) => {
		const bad = (message) => errors.push(`${pkg.path}: ${message}`);

		try {
			const {name} = pkg.json;

			if (
				name &&
				!name.startsWith('@liferay/') &&
				!ALLOWED_NAMED_SCOPE_EXCEPTIONS.includes(name)
			) {
				bad(
					`package name ${name} should be under @liferay/ named scope - https://git.io/JOgy7`
				);
			}
		}
		catch (error) {
			bad(`error thrown during checks: ${error}`);
		}
	});

	return errors;
}
